@Immutable
data class ColorFamily(
    val color: Color,
    val onColor: Color,
    val colorContainer: Color,
    val onColorContainer: Color,
)

val unspecified_scheme = ColorFamily(
    Color.Unspecified, Color.Unspecified, Color.Unspecified, Color.Unspecified
)

@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@Composable
fun AppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    enableExpressive: Boolean = true,
    isGallery: Boolean = false,
    textScale: Float = TextScale.DEFAULT,
    content: @Composable() () -> Unit,
) {
    val colorScheme = when {
        darkTheme -> darkScheme
        else -> lightScheme
    }
    val chaiColors = if (darkTheme) darkChaiColors else lightChaiColors

    val motionScheme = if (enableExpressive) MotionScheme.expressive() else MotionScheme.standard()

    CompositionLocalProvider(LocalChaiColors provides chaiColors) {
        MaterialExpressiveTheme(
            colorScheme = colorScheme,
            motionScheme = motionScheme,
            typography = (if (isGallery) GalleryTypography else AppTypography).scaled(textScale),
            content = content
        )
    }
}
